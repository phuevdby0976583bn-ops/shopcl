def split_message_text(text: str, max_length: int = 3800) -> list[str]:
    """Cat text an toan theo doan van de khong bao gio vuot qua gioi han 4096 ky tu cua Telegram."""
    if not text:
        return [""]
    if len(text) <= max_length:
        return [text]

    chunks: list[str] = []
    lines = text.split("\n")
    cur_chunk = ""

    for line in lines:
        if len(cur_chunk) + len(line) + 1 > max_length:
            if cur_chunk:
                chunks.append(cur_chunk.strip())
            cur_chunk = line + "\n"
        else:
            cur_chunk += line + "\n"

    if cur_chunk.strip():
        chunks.append(cur_chunk.strip())

    return chunks if chunks else [text[:max_length]]
